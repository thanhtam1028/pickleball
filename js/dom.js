// Thoát ký tự HTML cho mọi chuỗi do người dùng nhập trước khi chèn vào trang.
export function esc(value) {
  return String(value ?? '').replace(/[&<>"']/g, (c) => (
    { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]
  ));
}

